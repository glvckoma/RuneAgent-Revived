    private void saveScriptButtonActionPerformed(java.awt.event.ActionEvent evt) {
        String scriptName = javax.swing.JOptionPane.showInputDialog(this, 
                "Enter script name:", 
                "Save Script", 
                javax.swing.JOptionPane.PLAIN_MESSAGE);
        
        if (scriptName != null && !scriptName.trim().isEmpty()) {
            // Add .js extension if not present
            if (!scriptName.toLowerCase().endsWith(".js")) {
                scriptName += ".js";
            }
            
            java.io.File scriptFile = new java.io.File("scripts" + java.io.File.separator + scriptName);
            
            // Check if file exists and confirm overwrite
            if (scriptFile.exists()) {
                int result = javax.swing.JOptionPane.showConfirmDialog(this, 
                        "Script already exists. Overwrite?", 
                        "Confirm Overwrite", 
                        javax.swing.JOptionPane.YES_NO_OPTION);
                
                if (result != javax.swing.JOptionPane.YES_OPTION) {
                    return;
                }
            }
            
            try (java.io.FileWriter writer = new java.io.FileWriter(scriptFile)) {
                writer.write(scriptArea.getText());
                logEvent(eventLog, "Script saved to: " + scriptFile.getAbsolutePath());
                
                // Refresh the scripts list in the Scripts tab
                if (scriptsPanel != null) {
                    scriptsPanel.refreshScriptsList();
                }
            } catch (java.io.IOException e) {
                logEvent(eventLog, "Error saving script: " + e.getMessage());
                e.printStackTrace();
            }
        }
    }
    
    private void loadScriptButtonActionPerformed(java.awt.event.ActionEvent evt) {
        javax.swing.JFileChooser fileChooser = new javax.swing.JFileChooser();
        fileChooser.setDialogTitle("Load Script");
        fileChooser.setFileFilter(new javax.swing.filechooser.FileNameExtensionFilter("JavaScript Files (*.js)", "js"));
        
        if (fileChooser.showOpenDialog(this) == javax.swing.JFileChooser.APPROVE_OPTION) {
            java.io.File file = fileChooser.getSelectedFile();
            
            try (java.io.BufferedReader reader = new java.io.BufferedReader(new java.io.FileReader(file))) {
                StringBuilder content = new StringBuilder();
                String line;
                while ((line = reader.readLine()) != null) {
                    content.append(line).append("\n");
                }
                scriptArea.setText(content.toString());
                logEvent(eventLog, "Script loaded from: " + file.getAbsolutePath());
            } catch (java.io.IOException e) {
                logEvent(eventLog, "Error loading script: " + e.getMessage());
                e.printStackTrace();
            }
        }
    }
    
