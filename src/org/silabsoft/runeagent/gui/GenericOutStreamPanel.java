    /**
     * Updates the log toggle button style to make its state more visible
     */
    private void updateLogToggleStyle() {
        // Set custom colors for the toggle button
        logToggle.setFocusPainted(false);
        
        // Add an item listener to update the style when the toggle state changes
        logToggle.addItemListener(e -> {
            boolean isDarkMode = logToggle.getBackground().getRed() < 100;
            updateToggleButtonText(isDarkMode);
        });
        
        // Initial style update
        boolean isDarkMode = logToggle.getBackground().getRed() < 100;
        updateToggleButtonText(isDarkMode);
    }
    
    /**
     * Updates the toggle button text color based on the current state
     */
    private void updateToggleButtonText(boolean isDarkMode) {
        boolean isSelected = logToggle.isSelected();
        
        if (isSelected) {
            // Selected state - green text
            logToggle.setForeground(isDarkMode ? new Color(100, 255, 100) : new Color(0, 150, 0));
        } else {
            // Unselected state - red text
            logToggle.setForeground(isDarkMode ? new Color(255, 100, 100) : new Color(200, 0, 0));
        }
        
        // Keep the original text
        logToggle.setText("Log Incoming Packets");
    }

